/**
 * One-time codes.
 *
 * Monospace is not cosmetic here: a proportional font re-flows the whole code every time a digit
 * changes, which is exactly what happens once per period. Tabular, evenly tracked digits keep the
 * code stable and let the countdown morph around it without re-layout.
 */
val CodeStyle =
  TextStyle(
    fontFamily = FontFamily.Monospace,
    fontWeight = FontWeight.Medium,
    fontSize = 32.sp,
    lineHeight = 40.sp,
    letterSpacing = 4.sp,
  )

