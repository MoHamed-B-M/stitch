package com.stitch.authenticator.data.updates

/**
 * A version in the two shapes this repository writes them: `1.2.3` for a tagged release, and
 * `1.0-dev.18` for a CI build from `dev` (where the number is the workflow run that built it).
 *
 * Parsing is total and deliberately strict: anything that is not one of those two shapes is
 * `null`, and callers turn `null` into an honest "couldn't tell" instead of guessing at an
 * ordering that might offer a downgrade.
 */
data class AppVersion(
  val major: Int,
  val minor: Int,
  val patch: Int,
  /** The CI run number on an `x.y-dev.N` build; `null` on a tagged release. */
  val devBuild: Int? = null,
) : Comparable<AppVersion> {

  /** The release line this version sits on. A dev build's patch is always 0 by construction. */
  val stableBase: AppVersion
    get() = AppVersion(major, minor, patch)

  /**
   * Orders by release line first, then by build: a dev build ranks above the tagged release with
   * the same base (it was cut from a later commit), and two tagged releases compare by semver.
   */
  override fun compareTo(other: AppVersion): Int {
    val byLine = compareValuesBy(this, other, { it.major }, { it.minor }, { it.patch })
    if (byLine != 0) return byLine
    return compareValues(devBuild ?: 0, other.devBuild ?: 0)
  }

  override fun toString(): String =
    if (devBuild != null) "$major.$minor-dev.$devBuild" else "$major.$minor.$patch"
}

/** What a channel concluded about the installed build. */
sealed interface ChannelVerdict {
  /** The installed build is the newest one this channel has to offer. */
  data object UpToDate : ChannelVerdict

  /** The channel has a strictly newer build than the installed one. */
  data object Newer : ChannelVerdict

  /** A side of the comparison could not be read — never dressed up as [UpToDate]. */
  data object Unknown : ChannelVerdict
}

/**
 * The pure half of the updater: every rule that decides "is there something newer" lives here,
 * free of Android, the network and JSON, so the interesting cases are one-line tests.
 */
object UpdateVersions {

  private val stablePattern = Regex("""(\d+)\.(\d+)\.(\d+)""")
  private val devPattern = Regex("""(\d+)\.(\d+)-dev\.(\d+)""")
  private val buildNumberPattern = Regex("""#(\d+)""")

  /** Reads the installed `versionName` in either shape. */
  fun parseInstalled(versionName: String): AppVersion? =
    parseDev(versionName) ?: parseStable(versionName)

  /** Reads a release tag (`v1.2.3`); the leading `v` is decoration, not part of the number. */
  fun parseTag(tagName: String): AppVersion? = parseStable(tagName.removePrefix("v"))

  /** Reads the CI run number out of a `v-next` release title such as `Dev build #18`. */
  fun parseDevBuildNumber(title: String): Int? =
    buildNumberPattern.find(title)?.groupValues?.get(1)?.toIntOrNull()

  /**
   * The stable channel's rule: offer only a strictly newer release line. A dev install on base
   * 1.0 sees 1.0.1 (yes) and 1.0.0 (no) — [ChannelVerdict.Newer] can never mean a downgrade,
   * which matters because Android refuses to install a lower version code anyway.
   */
  fun stableVerdict(installed: AppVersion, release: AppVersion): ChannelVerdict =
    when {
      release.stableBase > installed.stableBase -> ChannelVerdict.Newer
      else -> ChannelVerdict.UpToDate
    }

  /**
   * The beta channel's rule: compare build numbers. Every CI build — dev or stable — carries the
   * workflow run number as its version code, so "the `v-next` release was built by run M" against
   * "this install came from run N" answers the question for either install flavor, and a stable
   * install that is already newer than the last dev push correctly reads as up to date.
   */
  fun betaVerdict(installedVersionCode: Long, releaseBuildNumber: Int?): ChannelVerdict =
    when {
      releaseBuildNumber == null -> ChannelVerdict.Unknown
      releaseBuildNumber > installedVersionCode -> ChannelVerdict.Newer
      else -> ChannelVerdict.UpToDate
    }

  /**
   * The release body as something worth reading in a card: real bullets when the notes have them
   * (stable releases, generated by GitHub), otherwise the body's own lines (the one-sentence note
   * CI writes for `v-next`). Capped so a long changelog cannot turn Settings into a wall.
   */
  fun releaseNotes(body: String, limit: Int = 6): List<String> {
    val bullets =
      body.lineSequence()
        .map { it.trim() }
        .filter { it.startsWith("* ") || it.startsWith("- ") }
        .map { it.removePrefix("* ").removePrefix("- ").trim() }
        .filter { it.isNotEmpty() }
        .toList()
    return bullets
      .ifEmpty { body.lineSequence().map { it.trim() }.filter { it.isNotEmpty() }.toList() }
      .take(limit)
  }

  private fun parseStable(text: String): AppVersion? =
    stablePattern.matchEntire(text)?.let { match ->
      val (major, minor, patch) = match.destructured
      AppVersion(major.toInt(), minor.toInt(), patch.toInt())
    }

  private fun parseDev(text: String): AppVersion? =
    devPattern.matchEntire(text)?.let { match ->
      val (major, minor, build) = match.destructured
      AppVersion(major.toInt(), minor.toInt(), 0, build.toInt())
    }
}
